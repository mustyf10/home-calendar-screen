"""Explicit recipe generation: Claude drafts ingredients, steps and servings for a recipe that has none.

A draft is not extraction: nothing here claims the recipe came from a source. The draft lives in
Dish.generated_recipe until the household approves it (writing only ingredients, steps and servings,
together) or discards it. Nothing is generated by opening a page, and a draft never touches the saved recipe.

Dish.generated_recipe: {"status": "queued"|"running"|"ready"|"failed", "attempt": token, "queued_at": iso,
"input": {"title", "description"}, "base": {"ingredients", "steps", "servings"}, "draft": {...} | None,
"error": str | None}. `base` is the saved state the draft was made for; approval and the worker's commit both
refuse to go on if the saved recipe no longer matches it. The column is JSON, so it is always replaced, never
edited in place.
"""
import logging
import math
import uuid
from datetime import datetime, timezone

from fastapi import APIRouter, Depends, HTTPException, Request
from fastapi.responses import RedirectResponse, Response
from sqlalchemy import func, null, or_, select, update
from sqlalchemy.orm import Session

from app.claude import NoResult, call_json
from app.config import config
from app.db import SessionLocal, get_session
from app.dishes.forms import _int_or_none, _lines
from app.errors import log_failure, user_message
from app.models import Dish
from app.web import render

log = logging.getLogger(__name__)
router = APIRouter()

ACTIVE = ("queued", "running")
NO_KEY = "Recipe generation needs an Anthropic API key. Set ANTHROPIC_API_KEY, then try again."
STALE = ("The recipe's ingredients, steps or servings changed after this draft was started, "
         "so it can't be approved without overwriting those changes. Discard it and generate again if you still want one.")
HAS_INGREDIENTS = "This recipe already has ingredients."

SYSTEM = """Write a plausible home-cooking recipe for the dish named below.
This is an invented draft, not a transcription: do not claim it comes from any source.
Use the title, and the description if there is one, as the only inputs.
Give every ingredient with a quantity (metric units), one ingredient per entry.
Give concise numbered-in-order steps without step numbers.
Give the number of servings as a positive integer.
Write in English."""

SCHEMA = {
    "type": "object",
    "properties": {
        "ingredients": {"type": "array", "items": {"type": "string"}},
        "steps": {"type": "array", "items": {"type": "string"}},
        "servings": {"type": "integer"},
    },
    "required": ["ingredients", "steps", "servings"],
    "additionalProperties": False,
}


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _snapshot(dish: Dish) -> dict:
    return {"ingredients": list(dish.ingredients or []), "steps": list(dish.steps or []), "servings": dish.servings}


def _state(dish: Dish) -> dict | None:
    gen = dish.generated_recipe
    return gen if isinstance(gen, dict) and gen.get("status") else None


def _stale(dish: Dish, gen: dict) -> bool:
    return gen.get("base") != _snapshot(dish)


def _lock(session: Session, dish_id: int) -> Dish:
    """Takes SQLite's write lock, then re-reads the recipe, so the checks that follow can't be overtaken by an
    edit between reading and writing. Pins updated_at: shopping lists are rebuilt when it moves."""
    session.execute(update(Dish).where(Dish.id == dish_id).values(updated_at=Dish.updated_at))
    dish = session.get(Dish, dish_id, populate_existing=True)
    if dish is None:
        session.rollback()
        raise HTTPException(404, "Recipe not found")
    return dish


def _try_lock(session: Session, dish_id: int) -> Dish | None:
    """_lock for the worker, where a recipe deleted meanwhile just ends the work."""
    try:
        return _lock(session, dish_id)
    except HTTPException:
        return None


def _store(session: Session, dish_id: int, state: dict | None, *, status: str | None = None,
           attempt: str | None = None) -> bool:
    """Replaces generated_recipe, only while it still has the given status and attempt (checked in the UPDATE
    itself). Draft metadata is not a recipe change, so updated_at stays put. False: it moved on, nothing written."""
    q = update(Dish).where(Dish.id == dish_id)
    if status is not None:
        q = q.where(func.json_extract(Dish.generated_recipe, "$.status") == status)
    if attempt is not None:
        q = q.where(func.json_extract(Dish.generated_recipe, "$.attempt") == attempt)
    changed = session.execute(
        q.values(generated_recipe=null() if state is None else state, updated_at=Dish.updated_at)
    ).rowcount
    return bool(changed)


def _with(gen: dict, **changes) -> dict:
    return {**gen, **changes}


def _failed(gen: dict, error: str) -> dict:
    return _with(gen, status="failed", error=error, draft=None)


# --- Claude ------------------------------------------------------------------

def generate_recipe(title: str, description: str) -> dict:
    """One structured call from the title (and description). Raises on an API error or an unusable draft."""
    text = f"TITLE:\n{title}" + (f"\n\nDESCRIPTION:\n{description}" if description else "")
    out = call_json(SYSTEM, [{"type": "text", "text": text}], SCHEMA, timeout=120)
    return validate_draft(out)


def validate_draft(out: dict) -> dict:
    ingredients = _clean_lines(out.get("ingredients"))
    steps = _clean_lines(out.get("steps"))
    servings = out.get("servings")
    if not ingredients:
        raise NoResult("the draft had no ingredients")
    if isinstance(servings, bool) or not isinstance(servings, (int, float)) or not math.isfinite(servings) \
            or servings != int(servings) or servings <= 0:
        raise NoResult("the draft had no valid serving count")
    return {"ingredients": ingredients, "steps": steps, "servings": int(servings)}


def _clean_lines(value) -> list[str]:
    if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
        return []
    return [v.strip() for v in value if v.strip()]


# --- Worker entry points -----------------------------------------------------

def next_dish(session: Session) -> int | None:
    """The oldest explicitly queued generation, or None."""
    queued = []
    for dish in session.scalars(select(Dish).where(Dish.generated_recipe.is_not(None))):
        gen = _state(dish)
        if gen and gen["status"] == "queued":
            queued.append((gen.get("queued_at") or "", dish.id))
    return min(queued)[1] if queued else None


def recover(session: Session) -> None:
    """Generation interrupted by a restart goes back to the queue (the same attempt, so no second click)."""
    for dish in session.scalars(select(Dish).where(Dish.generated_recipe.is_not(None))):
        gen = _state(dish)
        if gen and gen["status"] == "running":
            _store(session, dish.id, _with(gen, status="queued"), status="running", attempt=gen["attempt"])
    session.commit()


def run(dish_id: int) -> None:
    """Synchronous (the worker runs it in a thread). The Claude call happens with no transaction open."""
    with SessionLocal() as s:
        dish = _try_lock(s, dish_id)
        gen = _state(dish) if dish else None
        if not gen or gen["status"] != "queued":
            s.rollback()
            return
        attempt, given = gen["attempt"], gen["input"]
        if not config.anthropic_api_key:
            _store(s, dish_id, _failed(gen, NO_KEY), status="queued", attempt=attempt)
        else:
            _store(s, dish_id, _with(gen, status="running", error=None), status="queued", attempt=attempt)
        s.commit()
        if not config.anthropic_api_key:
            return

    draft, error = None, None
    try:
        draft = generate_recipe(given["title"], given["description"])
    except Exception as e:
        log_failure(log, f"Recipe generation for dish {dish_id} failed", e)
        error = user_message("Couldn't generate a recipe", e)

    with SessionLocal() as s:
        dish = _try_lock(s, dish_id)
        gen = _state(dish) if dish is not None else None
        if dish is None or not gen or gen["status"] != "running" or gen["attempt"] != attempt:
            s.rollback()  # discarded or restarted while Claude worked: this answer belongs to nothing
            return
        if error:
            new = _failed(gen, error)
        elif _stale(dish, gen):
            new = _failed(gen, STALE)
        else:
            new = _with(gen, status="ready", draft=draft, error=None)
        _store(s, dish_id, new, status="running", attempt=attempt)
        s.commit()


# --- Actions -----------------------------------------------------------------

def request_generation(session: Session, dish_id: int, attempt: str | None) -> None:
    """Queues generation once. Repeated clicks, a ready draft and recipes that have ingredients queue nothing.
    `attempt` is the token the page showed ("" for none): a stale tab's click is ignored."""
    dish = _lock(session, dish_id)
    gen = _state(dish)
    if attempt != (gen or {}).get("attempt", "") or dish.ingredients or (gen and gen["status"] != "failed"):
        session.rollback()
        return
    token = uuid.uuid4().hex  # never reused, even after a discard
    new: dict
    if not config.anthropic_api_key:
        new = {"status": "failed", "attempt": token, "error": NO_KEY, "draft": None}
    else:
        new = {
            "status": "queued", "attempt": token, "queued_at": _now(),
            "input": {"title": dish.title, "description": dish.description or ""},
            "base": _snapshot(dish), "draft": None, "error": None,
        }
    if gen:  # a retry replaces the failure it saw, and nothing newer
        wrote = _store(session, dish_id, new, status="failed", attempt=gen["attempt"])
    else:
        wrote = bool(session.execute(
            update(Dish).where(Dish.id == dish_id, or_(Dish.generated_recipe.is_(None), func.json_type(Dish.generated_recipe) == "null"))
            .values(generated_recipe=new, updated_at=Dish.updated_at)).rowcount)
    session.commit() if wrote else session.rollback()


OUTDATED = "This page is out of date: the draft was replaced or discarded. Review the current one below."


def approve(session: Session, dish_id: int, attempt: str | None, ingredients_text: str, steps_text: str,
            servings_text: str):
    """Saves the reviewed ingredients, steps and servings together. Returns (errors, stale).

    The write is one UPDATE that only matches while the draft is still this ready attempt and the saved fields
    still equal its snapshot, so a concurrent edit can't be overwritten. Unlike draft metadata it moves
    updated_at, because the ingredients really change."""
    errors: dict = {}
    ingredients, steps = _lines(ingredients_text), _lines(steps_text)
    servings = _int_or_none(servings_text)
    if not ingredients:
        errors["ingredients"] = "Add at least one ingredient."
    if servings_text.strip() and not servings:  # unreadable, or zero
        errors["servings"] = "Servings must be a whole number above zero."
    if errors:
        return errors, False
    dish = _lock(session, dish_id)  # write lock held until commit: the snapshot below can't go stale
    gen = _state(dish)
    if not gen or gen["status"] != "ready":
        session.rollback()
        return {"draft": "There is no draft to approve."}, False
    if gen["attempt"] != attempt:  # a form from an older draft must not approve its replacement
        session.rollback()
        return {"outdated": OUTDATED}, False
    if _stale(dish, gen):
        session.rollback()
        return {}, True
    wrote = session.execute(
        update(Dish).where(
            Dish.id == dish_id,
            func.json_extract(Dish.generated_recipe, "$.status") == "ready",
            func.json_extract(Dish.generated_recipe, "$.attempt") == gen["attempt"],
        ).values(ingredients=ingredients, steps=steps, servings=servings, generated_recipe=null())
    ).rowcount
    if not wrote:
        session.rollback()
        return {}, True
    session.commit()
    return {}, False


def discard(session: Session, dish_id: int, attempt: str | None) -> None:
    """Drops the draft (or failure) and leaves the saved recipe alone. A running or queued request is cancelled:
    its answer is thrown away when it arrives. A stale tab's discard (another attempt) does nothing."""
    gen = _state(_lock(session, dish_id))
    if gen and gen["attempt"] == attempt:
        _store(session, dish_id, None, attempt=attempt)
        session.commit()
    else:
        session.rollback()


# --- Templates ---------------------------------------------------------------

def detail_context(dish: Dish) -> dict:
    """Everything dishes/_generation.html and generated_recipe.html need; pass as `generation`."""
    gen = _state(dish)
    status = gen["status"] if gen else None
    draft = (gen or {}).get("draft") or {}
    configured = bool(config.anthropic_api_key)
    return {
        "status": status,
        "attempt": (gen or {}).get("attempt", ""),
        "active": status in ACTIVE,
        "error": (gen or {}).get("error"),
        "configured": configured,
        "can_generate": not dish.ingredients and (gen is None or status == "failed"),
        "stale": bool(gen and status == "ready" and _stale(dish, gen)),
        "stale_message": STALE,
        "no_key": NO_KEY,
        "ingredients_text": "\n".join(draft.get("ingredients") or []),
        "steps_text": "\n".join(draft.get("steps") or []),
        "servings": draft.get("servings") or "",
        "visible": gen is not None or not dish.ingredients,
    }


def _attempt(form) -> str | None:
    value = form.get("attempt")
    return value if isinstance(value, str) else None


def _dish_or_404(session: Session, dish_id: int) -> Dish:
    dish = session.get(Dish, dish_id, populate_existing=True)
    if dish is None:
        raise HTTPException(404, "Recipe not found")
    return dish


def _page(request: Request, dish: Dish, status_code: int = 200, **extra):
    generation = {**detail_context(dish), **extra}
    return render(request, "dishes/generated_recipe.html", {"dish": dish, "generation": generation},
                  status_code=status_code)


@router.get("/dishes/{dish_id}/generate")
def review(request: Request, dish_id: int, session: Session = Depends(get_session)):
    return _page(request, _dish_or_404(session, dish_id))


@router.get("/dishes/{dish_id}/generate/status")
def status(request: Request, dish_id: int, session: Session = Depends(get_session)):
    dish = session.get(Dish, dish_id, populate_existing=True)
    if dish is None:
        raise HTTPException(404, "Recipe not found")
    generation = detail_context(dish)
    if not generation["active"]:
        return Response(headers={"HX-Refresh": "true"})  # finished: the page shows the draft or the failure
    return render(request, "dishes/_generation.html", {"dish": dish, "generation": generation})


@router.post("/dishes/{dish_id}/generate")
async def generate(request: Request, dish_id: int, session: Session = Depends(get_session)):
    dish = _dish_or_404(session, dish_id)
    request_generation(session, dish.id, _attempt(await request.form()))
    return RedirectResponse(f"/dishes/{dish.id}/generate", status_code=303)


@router.post("/dishes/{dish_id}/generate/approve")
async def approve_draft(request: Request, dish_id: int, session: Session = Depends(get_session)):
    _dish_or_404(session, dish_id)
    form = await request.form()
    text = {k: form.get(k) or "" for k in ("ingredients_text", "steps_text", "servings")}
    errors, stale = approve(session, dish_id, _attempt(form), text["ingredients_text"], text["steps_text"],
                            text["servings"])
    dish = session.get(Dish, dish_id, populate_existing=True)
    if "outdated" in errors:  # show what is current, not the old tab's text
        return _page(request, dish, 409, errors=errors)
    if errors or stale:
        return _page(request, dish, 409 if stale else 422, errors=errors, conflict=stale,
                     ingredients_text=text["ingredients_text"], steps_text=text["steps_text"],
                     servings=text["servings"])
    return RedirectResponse(f"/dishes/{dish.id}", status_code=303)


@router.post("/dishes/{dish_id}/generate/discard")
async def discard_draft(request: Request, dish_id: int, session: Session = Depends(get_session)):
    dish = _dish_or_404(session, dish_id)
    discard(session, dish.id, _attempt(await request.form()))
    return RedirectResponse(f"/dishes/{dish.id}", status_code=303)
